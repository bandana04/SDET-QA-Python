#Inheritance : Acquiring all the attributes(variables) and behaviour(methods) from one class to another class
#class A --> a,b,c  m1() m2()  --> A is parent of B class  (Base class/Super class)
#class B --> x,y,z  m3()  --> B is child of A class  (Sub class/Derived class)

#Objectives of Inheritance
#1. Code re-usability
#2. Avoid duplication

#TYpes of inheritance
#1. single
#2. multilevel
#3. hierarchy
#4. multiple

