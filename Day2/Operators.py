#Arithmetic operators
a = 5
b = 2

print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a//b) #quotient
print(a%b)  #remainder
print(a**b)  #square of

#Relational --> >, <, >= , <=, !=, ==
p = 5
q = 10

print(p>q)
print(p<q)
print(p<=q)
print(p>=q)
print(p==q)
print(p!=q)

#Logical operators --> AND, OR, NOT
d = True
e = False

print(d and e)
print(not d)
print(d or e)